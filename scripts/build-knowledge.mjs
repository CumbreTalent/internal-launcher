#!/usr/bin/env node
// Builds the Knowledge tile from data/knowledge.json, the single source:
//
//   node scripts/build-knowledge.mjs
//
//   knowledge.html            the page for everyone: the template with the data
//                             inlined, minus the admin-only `sales` block
//   api/_knowledge-sales.js   the `sales` block alone, for /api/knowledge, which
//                             serves it to admins (and refuses everyone else)
//
// Commit both outputs; `npm test` fails when they are out of date. data/ is in
// .vercelignore, so the full JSON (with the sales material) never deploys: an
// assistant's browser cannot fetch it as a static file, and the only copy of
// the sales block on the server sits behind the role check.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCE = path.join(ROOT, 'data', 'knowledge.json')
export const TEMPLATE = path.join(ROOT, 'scripts', 'knowledge-template.html')
export const PAGE = path.join(ROOT, 'knowledge.html')
export const SALES_MODULE = path.join(ROOT, 'api', '_knowledge-sales.js')

// Pure: { page, salesModule } from the data object and the template text.
export function build(data, template) {
  if (!template.includes('__DATA__')) throw new Error('template has no __DATA__ placeholder')
  const { sales, ...shared } = data
  if (!sales) throw new Error('knowledge.json has no sales block')
  // Inside a <script>, "<" must never form "</script>" or "<!--": escape every one.
  const blob = JSON.stringify(shared).replace(/</g, '\\u003c')
  const page = template.replace('__DATA__', () => blob)
  const salesModule = [
    '// GENERATED by scripts/build-knowledge.mjs from data/knowledge.json; do not edit.',
    '//',
    '// The admin-only `sales` block of the Knowledge Center. Server-side only: the',
    '// underscore keeps Vercel from deploying it as a route, and /api/knowledge',
    '// serves it to admins after checking the launcher role. It is not in',
    '// knowledge.html, and data/ never deploys, so this is the only copy an',
    '// assistant could ever ask the server for, and the server says no.',
    `export const SALES = ${JSON.stringify(sales, null, 2)}`,
    '',
  ].join('\n')
  return { page, salesModule }
}

export function readSource() {
  return {
    data: JSON.parse(fs.readFileSync(SOURCE, 'utf8')),
    template: fs.readFileSync(TEMPLATE, 'utf8'),
  }
}

export function buildFromDisk() {
  const { data, template } = readSource()
  return build(data, template)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { page, salesModule } = buildFromDisk()
  fs.writeFileSync(PAGE, page)
  fs.writeFileSync(SALES_MODULE, salesModule)
  console.log(`wrote ${path.relative(ROOT, PAGE)} (${page.length} chars) and ${path.relative(ROOT, SALES_MODULE)} (${salesModule.length} chars)`)
}
